#!/usr/bin/env node
// The Homebrew cask for one release: `brew install --cask liuscraft/tap/pi-desktop`.
// `release.yml` runs it after the dmgs are on the release and pushes the result to
// liuscraft/homebrew-tap; `make cask` runs it against dist/ to see what the tap would carry.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const CASK = 'pi-desktop';
const APP = 'Pi Desktop';
const REPO = 'liuscraft/pi-desktop';
const DESC = 'Desktop app for the pi coding agent';
/** electron-builder's mac.minimumSystemVersion, as a Homebrew macos symbol. */
const MIN_MACOS = 'monterey';
const ARCHES = [
  { homebrew: 'arm', electron: 'arm64' },
  { homebrew: 'intel', electron: 'x64' },
];
const EXIT_FAILURE = 1;

class FatalError extends Error {}
const fail = (message) => {
  throw new FatalError(message);
};

function parseArgs(argv) {
  const flags = {};
  for (const arg of argv) {
    const match = /^--([a-z-]+)=(.*)$/.exec(arg);
    if (!match) fail(`unknown argument: ${arg}`);
    flags[match[1]] = match[2];
  }
  return flags;
}

/** The dmg a release carries for one architecture (`electron-builder`'s artifactName). */
const dmgName = (version, arch) => `Pi-Desktop-${version}-${arch}.dmg`;

function sha256(file) {
  return new Promise((resolve, reject) => {
    const hash = createHash('sha256');
    fs.createReadStream(file)
      .on('error', reject)
      .on('data', (chunk) => hash.update(chunk))
      .on('end', () => resolve(hash.digest('hex')));
  });
}

function caskFile(arch) {
  return `  on_${arch.homebrew} do
    sha256 "${arch.sha256}"
    url "https://github.com/${REPO}/releases/download/v#{version}/Pi-Desktop-#{version}-${arch.electron}.dmg",
        verified: "github.com/${REPO}/"
  end`;
}

function render({ version, arches }) {
  return `# Generated by scripts/cask.mjs from the released dmgs; do not edit by hand.
cask "${CASK}" do
  version "${version}"

${arches.map((arch) => caskFile(arch)).join('\n\n')}

  name "${APP}"
  desc "${DESC}"
  homepage "https://github.com/${REPO}"

  livecheck do
    url :url
    strategy :github_latest
  end

  depends_on macos: ">= :${MIN_MACOS}"

  app "${APP}.app"

  zap trash: [
    "~/.pi-desktop",
    "~/Library/Application Support/${APP}",
    "~/Library/Caches/dev.pi-desktop.app",
    "~/Library/Preferences/dev.pi-desktop.app.plist",
    "~/Library/Saved Application State/dev.pi-desktop.app.savedState",
  ]
end
`;
}

async function main() {
  const flags = parseArgs(process.argv.slice(2));
  const version = flags.version;
  if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) fail('pass the release version as --version=x.y.z');
  const dist = flags.dist ?? 'dist';

  const arches = [];
  for (const arch of ARCHES) {
    const file = path.join(dist, dmgName(version, arch.electron));
    if (!fs.existsSync(file)) fail(`missing ${file}: build both architectures first`);
    arches.push({ ...arch, sha256: await sha256(file) });
  }
  const text = render({ version, arches });

  if (!flags.out) {
    process.stdout.write(text);
    return;
  }
  fs.mkdirSync(path.dirname(flags.out), { recursive: true });
  fs.writeFileSync(flags.out, text);
  process.stdout.write(`→ ${flags.out}\n`);
}

main().catch((error) => {
  if (error instanceof FatalError) {
    process.stderr.write(`error: ${error.message}\n`);
    process.exit(EXIT_FAILURE);
  }
  throw error;
});
